"""
Inheritance strategy benchmark utility that compares the class table
and the concrete table strategies across the whole set of CRUD
operations, using hand written SQLite queries.

Builds both schemas in temporary databases and times schema creation,
bulk insert, select by identifier, full scan, count, bulk update and
bulk delete for each of them, printing a report with the elapsed time
per operation and the resulting speedup. A second section repeats a
subset of the operations over a wide hierarchy (twenty columns per
level, sixty in total) to show how the balance shifts once the rows of
the flattened table become significantly wider.

Note that the queries are written by hand rather than generated by the
ORM, so the report measures the cost of the joins alone and not the
cost of an actual retrieval, where the building of the entities
dominates by a wide margin. Treat the numbers as an upper bound on
what the strategy may save, and not as a prediction of the gain of an
application level operation.

Run from the project root with:
    python scripts/benchmark_inheritance.py [iterations]

Where iterations is the number of rows used in the bulk operations,
defaulting to one thousand.

The benchmark logic lives in the entity manager plugin, under
`data/src/entity_manager/benchmark.py`, so that it is covered by the
plugin test suite, this file is only the command line entry point.
"""

